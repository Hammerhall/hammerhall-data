package io.hammerhall.data.mov.site;

import java.util.Map;

/**
 * Раздел SOURCE.md о синтетике «Свартальвхейм»: что выдумано, а что настоящее, как устроены время и срез, профили,
 * узоры и заложенные отклонения — словами, без чисел ответов. Зовёт {@code MovDocs}.
 */
public final class SiteDocs {
    private SiteDocs() {
    }

    /** Раздел для SOURCE.md; {@code synthetic} — поле манифеста {@link SiteModule#manifest}, {@code profile} — профиль. */
    public static String section(Map<String, Object> synthetic, String profile) {
        StringBuilder sb = new StringBuilder();
        sb.append("""
                ## Синтетика: онлайн-кинотеатр «Свартальвхейм»

                Девятнадцать таблиц групп «Сервис», «Зрители» и «Сообщество» — **синтетика генератора**: выдуманный
                русскоязычный онлайн-кинотеатр (работает с 2019 года) и его сообщество вокруг **настоящих** фильмов набора.
                **Всё, что касается людей сервиса и их действий, выдумано**: пользователи (логины, имена, пол, год рождения),
                устройства, тарифы и цены, промокоды, подписки и оплаты, каталог сервиса с окнами прав, прокат и покупки,
                просмотры, оценки, рецензии, голоса, списки «посмотреть», подписки друг на друга, подборки и теги. Совпадения
                с настоящими людьми и учётными записями случайны. Настоящее в них — только фильмы (`movie_id`), их название,
                год, хронометраж, жанры, режиссёры и актёры, которые упоминают рецензии, и города пользователей: `city_id` —
                id города набора World (`wld-data-v1`, `cities.id` = geonameid), мягкая ссылка без внешнего ключа.

                * **Оценки согласованы с рейтингом**: оценка складывается из `movies.rank` фильма, «щедрости» пользователя,
                  его сродства к жанрам фильма, усталости и шума (скрытая модель генератора, в выпуске её нет); средняя оценка
                  фильма растёт с рейтингом, но у части фильмов «народная» оценка заметно расходится с рейтингом. Сам рейтинг
                  — синтетический (выше), это не оценки настоящих зрителей.
                * **Время**: окно — с 1 октября 2025 года; срез фактов — min(«сейчас», конец окна + 1 сутки); событий после
                  среза в выпуске нет, у подписок, проката, просмотров и списков «в пути» — состояние на срез. Предыстория —
                  только у пользователей и устройств (регистрация с 2019 года), подписок, шедших на начало окна (их начало —
                  настоящее, раньше окна), и каталога; оплаты, просмотры, оценки и прочие события — только внутри окна.
                  Суточный ход просмотров — по поясу города пользователя. Моменты — секунды Unix (UTC), деньги — рубли с
                  копейками. `id` — по моменту появления: продление окна
                  дописывает новые строки, прежние не меняются (кроме состояния «в пути»).
                * **Тарифы**: бесплатный с рекламой, базовый, стандарт, семейный и годовые к ним; цены — ступенями
                  (`plan_prices`), с 1 марта 2026 года — повышение около 10 %. Пробный период — 7 или 14 дней (по каналу и
                  промокоду); неудачное списание повторяется через 1 и 3 дня, после трёх неудач подписка истекает.
                * **Каталог** — не все фильмы профиля, а около шестой части: чаще известные, на русском языке или из России,
                  новые; фильм приходит и уходит окнами, часть возвращается. Доступ — по подписке, прокатом и покупкой
                  (новинки и часть известных: первые месяцы — только прокат и покупка, прокат в первые 60 дней дороже) или
                  бесплатно с рекламой.
                * **Тексты** рецензий, названия подборок и теги — по-русски, из словаря генератора; рецензия упоминает
                  настоящие жанр, год, режиссёра и актёров фильма, тон — по оценке; рецензии не повторяются.
                * **Узоры** для задач заложены: вечерние и выходные просмотры, пик новогодних каникул и провал июля, всплеск
                  просмотров новинок каталога, отмены после повышения цен, конверсия пробного периода, J-образные оценки,
                  голоса с тяжёлым хвостом, граф подписок с предпочтительным присоединением, список «посмотреть», семейный
                  тариф с одновременными просмотрами. **Малой долей заложены и отклонения** — для задач «найди аномалию»:
                  двойные списания с возвратом, оценки без просмотра («смотрел раньше»), просмотры дольше хронометража,
                  скрытые рецензии удалённых пользователей, досмотр проката после ухода фильма из каталога, рецензии с
                  оценкой, которую потом поменяли. Их доли в выпуск не пишутся.
                """);
        sb.append("* **Профиль `").append(profile).append("`**: ");
        sb.append(switch (profile) {
            case "full" -> "все фильмы набора и полный масштаб пользователей";
            case "medium" -> "фильмы профиля `medium` и 10 % пользователей (масштабом, не обрезкой)";
            default -> "фильмы профиля `small` и 1 % пользователей (масштабом, не обрезкой)";
        });
        sb.append("; каталог — та же доля от фильмов профиля.");
        Object cut = synthetic == null ? null : synthetic.get("cutoff");
        if (cut != null) sb.append(" Срез этого выпуска — ").append(cut).append('.');
        sb.append("\n\n");
        return sb.toString();
    }
}
