    private final List<String> tags;

    public StubTexts() {
        Set<String> t = new LinkedHashSet<>(List.of(TAG_BASE));
        outer:
        for (String m : TAG_MOOD) {
            for (String w : TAG_MORE) {
                if (t.size() >= 200) break outer;
                t.add(m + " " + w);
            }
        }
        tags = Collections.unmodifiableList(new ArrayList<>(t));
    }

    @Override
    public String login(Rng r) {
        String a = r.pick(LOGIN_WORDS);
        StringBuilder sb = new StringBuilder(a);
        if (r.chance(0.5)) sb.append('_').append(r.pick(LOGIN_WORDS));
        if (r.chance(0.8)) sb.append(r.between(1, 9999));
        while (sb.length() < 4) sb.append(r.nextInt(10));
        String s = sb.toString();
        return s.length() > 20 ? s.substring(0, 20) : s;
    }

    @Override
    public String displayName(Rng r, char gender) {
        String n = gender == 'F' ? r.pick(FEMALE) : r.pick(MALE);
        return n + " " + LETTERS.charAt(r.nextInt(LETTERS.length())) + ".";
    }

    static int tone(int rating) {
        return rating <= 4 ? 0 : rating <= 6 ? 1 : rating <= 8 ? 2 : 3;
    }

    @Override
    public String reviewTitle(Rng r, ReviewContext c) {
        String[] t = TITLE_BY_TONE[tone(c.rating())];
        return t[r.nextInt(t.length)];
    }

    private static String name(ReviewContext c) {
        return c.titleRu() != null ? c.titleRu() : c.title();
    }

    @Override
    public String reviewBody(Rng r, ReviewContext c) {
        int tone = tone(c.rating());
        List<String> s = new ArrayList<>();
        s.add(OPEN_BY_TONE[tone][r.nextInt(OPEN_BY_TONE[tone].length)]);
        String genre = c.genreIds().isEmpty() ? "кино" : GENRE_RU[c.genreIds().get(r.nextInt(c.genreIds().size()))];
        s.add("«" + name(c) + "» (" + c.year() + ") — " + genre + ", и это чувствуется в каждой сцене.");
        if (c.director() != null && r.chance(0.8)) s.add("Режиссёр " + c.director() + " держит интонацию до конца.");
        if (!c.actors().isEmpty() && r.chance(0.8)) {
            s.add(c.actors().size() > 1 && r.chance(0.6)
                    ? c.actors().get(0) + " и " + c.actors().get(1) + " играют убедительно."
                    : c.actors().get(0) + " в главной роли — на своём месте.");
        }
        if (c.otherTitle() != null && r.chance(0.4)) s.add("По сравнению с «" + c.otherTitle() + "» это шаг "
                + (tone >= 2 ? "вперёд." : "назад."));
        if (s.size() < 5 && r.chance(0.6)) s.add(MIDDLE[r.nextInt(MIDDLE.length)]);
        s.add(END_BY_TONE[tone][r.nextInt(END_BY_TONE[tone].length)] + " Моя оценка — " + c.rating() + " из 10.");
        // последний элемент — два предложения: всего не больше шести
        while (s.size() > 5) s.remove(s.size() - 2);
        return String.join(" ", s);
    }

    @Override
    public String collectionTitle(Rng r, int genreId) {
        String g = genreId >= 1 && genreId < GENRE_RU.length ? GENRE_RU[genreId] : "кино";
        String f = COLLECTION[r.nextInt(COLLECTION.length)];
        String s = String.format(Locale.ROOT, f, g);
        return Character.toUpperCase(s.charAt(0)) + s.substring(1);
    }

    @Override
    public List<String> tags() {
        return tags;
    }
