package io.hammerhall.data.auc.bid;

/** Почему ставка отклонена; у принятой — {@link #NONE}. */
public enum RejectReason {
    NONE(""),
    /** Ниже минимальной: меньше {@code текущая + шаг} (или стартовой цены), и участник это видел — ошибка ввода. */
    BELOW_MINIMUM("below_minimum"),
    /** Пока ставка шла, цену подняла чужая ставка (в более раннюю миллисекунду) — теперь сумма ниже минимальной. */
    PRICE_CHANGED("price_changed"),
    /**
     * Проиграла гонку: в ту же миллисекунду раньше по номеру приёма принята другая ставка; пришла бы первой — была бы
     * принята.
     */
    RACE_LOST("race_lost"),
    /** Равна максимуму лидера, поставленному раньше: при равных побеждает более ранний — лидер поднимается до неё. */
    TIED("tied"),
    /** Участник уже ведёт лот: повтор ставки (двойное нажатие, повтор после обрыва связи). */
    ALREADY_LEADING("already_leading"),
    /** Пришла после закрытия лота (онлайн) или после удара молотка (живые). */
    AFTER_CLOSE("after_close");

    private final String code;

    RejectReason(String code) {
        this.code = code;
    }

    /** Значение для данных; у {@link #NONE} — пустая строка (NULL). */
    public String code() {
        return code;
    }
}
