package io.hammerhall.data.auc.bid;

/**
 * Узор поведения участника на лоте. Стратегия решает, когда участник смотрит лот, сколько ставит и как отвечает на
 * перебитую ставку; сумма никогда не выше его максимума ({@link Bidder#max()}). В событиях стратегии не видно.
 *
 * <p>Онлайн (лот открыт дни): {@link #EARLY} ставит в первой половине срока минимальными шагами и возвращается через
 * часы; {@link #SNIPER} ставит свой максимум в последние секунды (бывает — опаздывает); {@link #WAR} — один из двух
 * «воюющих»: приходит под конец и отвечает на перебитую ставку за секунды, отсюда цепочки продлений;
 * {@link #CAUTIOUS} — редкие минимальные ставки, медленные ответы, сдаётся раньше максимума; {@link #MAX} — «по
 * максимуму»: один раз ставит автоставку на свой максимум и больше не приходит; {@link #SHILL} — подставной,
 * связан с продавцом: разгоняет цену минимальными шагами, пока есть настоящий соперник, и уходит до конца торгов.
 *
 * <p>Живые торги: те же узоры как готовность и скорость в зале — ранний вступает сразу и выходит раньше, поздний
 * вступает после последнего предупреждения аукциониста, воюющие отвечают друг другу без пауз, осторожный медлит и
 * выходит раньше максимума, «по максимуму» торгуется до конца. Заочный участник ({@link Channel#ABSENTEE}) — всегда
 * автоставка, стратегия у него не важна.
 *
 * <p>{@link #BOOK} — поручение «из книги» на живых торгах: аукционист исполняет максимум как заочную ставку (раньше
 * оставленное — первым) в канале участника. Так исполняется телефонная заявка, когда до участника не дозвонились, —
 * страховочная ставка с каналом {@link Channel#PHONE} ({@link Bidder#phoneStandIn}).
 *
 * <p>{@link #SCRIPTED} — участник без своего поведения: только действия из сценария ({@link Action}), для тестов и
 * особых случаев генератора.
 */
public enum Strategy {
    EARLY("early"),
    SNIPER("sniper"),
    WAR("war"),
    CAUTIOUS("cautious"),
    MAX("max"),
    SHILL("shill"),
    SCRIPTED("scripted"),
    BOOK("book");

    private final String code;

    Strategy(String code) {
        this.code = code;
    }

    public String code() {
        return code;
    }
}
