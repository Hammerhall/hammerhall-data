    /** Человек: имя, отчество (или {@code null}), фамилия. */
    public record Person(String first, String patronymic, String last, boolean female) {
    }

    public static Person person(Rng r, boolean female, double patronymicShare) {
        String first = female ? FEMALE[r.nextInt(FEMALE.length)] : MALE[r.nextInt(MALE.length)];
        String[] p = PATRONYMIC[r.nextInt(PATRONYMIC.length)];
        String last = SURNAMES[r.nextInt(SURNAMES.length)];
        if (female) last = femaleSurname(last);
        return new Person(first, r.chance(patronymicShare) ? (female ? p[1] : p[0]) : null, last, female);
    }

    /** Женская форма фамилии: -ов/-ев/-ин/-ын → +а, -ский/-цкий → -ая; прочие (-ко) — без изменений. */
    public static String femaleSurname(String m) {
        if (m.endsWith("ий")) return m.substring(0, m.length() - 2) + "ая";
        if (m.endsWith("ов") || m.endsWith("ев") || m.endsWith("ёв") || m.endsWith("ин") || m.endsWith("ын")) return m + "а";
        return m;
    }

    /** Название организации по виду: «Галерея «Охра»», «Антикварный салон «Патина»». */
    public static String firm(Rng r, String kindRu) {
        return kindRu + " «" + FIRM_WORDS[r.nextInt(FIRM_WORDS.length)] + "»";
    }
