    /** Родительный падеж мужской фамилии: «Сухотин» → «Сухотина», «Высоцкий» → «Высоцкого». */
    public static String genitive(String m) {
        if (m.endsWith("ий")) return m.substring(0, m.length() - 2) + "ого";
        if (m.endsWith("ов") || m.endsWith("ев") || m.endsWith("ёв") || m.endsWith("ин") || m.endsWith("ын")) return m + "а";
        return m;
    }

