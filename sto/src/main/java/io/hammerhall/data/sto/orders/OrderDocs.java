package io.hammerhall.data.sto.orders;

import java.util.List;
import java.util.Map;

/** Раздел SOURCE.md о заказах и сайте — качественно, без долей и чисел заложенного. */
public final class OrderDocs {
    private OrderDocs() {
    }

    /** Текст раздела; пусто, если таблиц заказов в прогоне нет. */
    public static String section(List<Map<String, Object>> files) {
        boolean orders = false;
        for (Map<String, Object> f : files) if ("orders".equals(f.get("table"))) orders = true;
        if (!orders) return "";
        return """
                ## Заказы и сайт

                * **Кто и когда** — первые заказы новых клиентов и повторные заказы активных: чаще у активных, с сезоном,
                  днём недели и пиками распродаж; час — по местному времени города покупателя (вечером больше). Канал —
                  сайт, приложение (у тех, кто обычно заходит с телефона через приложение) и телефон (чаще у старших и у
                  организаций, в часы работы операторов).
                * **Корзина** (`order_items`) — товары любимых отделов покупателя или общего спроса: популярность с тяжёлым
                  хвостом, жизненный цикл модели (разгон после запуска, спад, после выхода нового поколения старое
                  покупают заметно реже, перед снятием — распродажа), сезон вида. К устройству докладывают
                  подходящие аксессуары и спутники («покупают вместе»). Организации заказывают реже, но много строк и
                  штук. Товар покупают у магазина (`seller_id` пусто) или у продавца маркетплейса (`seller_id`,
                  `offer_id` — строка предложения, действующая в момент заказа).
                * **Цена и скидки** — цена строки (`unit_price`) — цена магазина или предложения продавца на момент заказа.
                  Акции магазина действуют на его товары: процент, сумма с единицы, «n+m» (самые дешёвые единицы —
                  бесплатно), «вместе дешевле» (от двух разных целевых товаров), промокоды (введённый код — в
                  `orders.promo_code`, даже если не подошёл по порогу); несуммируемая акция — сама по себе (берётся
                  лучшая), суммируемые складываются от остатка; `promo_id` строки — акция с самой большой долей её
                  скидки, `discount` — вся скидка строки. Строки продавцов — без акций магазина.
                * **НДС** — `vat_rate` — ставка на дату заказа по Москве: у магазина 20 % до 31.12.2025 и 22 % с 01.01.2026,
                  у продавца — по его режиму (общий — так же; на УСН — 0 %, 5 % или 7 %); `vat_amount` — НДС, входящий в
                  сумму строки после скидки. `orders.vat_amount` — НДС строк и доставки (доставку оказывает магазин).
                * **Суммы заказа** — `items_amount` = Σ `unit_price · qty`, `discount_amount` = Σ `discount`,
                  `total_amount` = `items_amount − discount_amount + delivery_amount`. Доставка — по способу и сумме
                  (выше порога — бесплатно).
                * **Исполнение** — товар магазина и продавцов FBO берут со складов магазина: ближайший к покупателю
                  городской склад, нет там — РЦ округа, нет и там — хаб (`order_items.warehouse_id` — склад отбора). Нет
                  товара нигде — покупатель видит, когда придёт: ждёт (чем дольше ждать, тем реже) или убирает строку
                  (в сессии — `remove_from_cart`); дождавшиеся строки собираются, как только товар пришёл; не
                  дождавшиеся — заказ отменяется. Продавец FBS собирает и передаёт посылку сам, своим сроком.
                * **Последняя миля** — у хаба и РЦ зон доставки нет: отгрузка (`shipments`) — всегда со склада последней
                  мили — для пункта выдачи это склад, к которому он привязан, для курьера и почты — ближайший к адресу
                  городской склад; товар с хаба, РЦ и посылки продавцов приходят туда транзитом. Зона и перевозчик —
                  этого склада: пункт выдачи — своей курьерской службой или партнёрской сетью, курьер — в зоне склада
                  (часть — экспресс), вне курьерских зон — почта (в зоне почты или вне зон: `zone_id` пусто). Заказ с
                  товаром магазина и посылками продавцов FBS — несколько отгрузок.
                * **Статусы** (`order_status_log`) — весь журнал: `created` → `paid` → `assembling` → `assembled` →
                  `shipped` → (`ready_for_pickup`) → `delivered` → (`returned`, если вернули весь заказ), отмена
                  (`cancelled`) — до сборки или после отгрузки (не забрали из пункта выдачи, отказ курьеру, утеря). Бывают
                  откаты: пересборка (`assembled` → `assembling`), посылка вернулась на склад до отправки (`shipped` →
                  `assembled`), перенаправление в другой пункт выдачи (`ready_for_pickup` → `shipped`). При оплате при
                  получении статуса `paid` в журнале нет — `paid_at` равен `delivered_at`. Поля моментов заказа —
                  последний момент своего статуса; `status` — статус на «сейчас».
                * **Платежи** (`payments`) — попытки по порядку (`seq`): карта, СБП, рассрочка (у дорогих заказов —
                  заметно чаще, срок — `installments`), сертификат и баллы (частью суммы), при получении; отказ банка
                  (`failed`, у СБП — и `cancelled`) — повтор тем же или другим способом, не оплатил — заказ отменяется.
                  Возврат денег — отрицательная сумма со статусом `refunded` тем же способом. Сумма успешных платежей за
                  вычетом возвратов равна сумме заказа минус возвращённое по возвратам (кроме неоплаченных и отменённых,
                  у отменённых — ноль).
                * **Доставка** — план отгрузки — сборка плюс транзит до склада последней мили; факт позже на задержку
                  передачи (в пики распродаж — до пары суток); в пути — базовый срок зоны с поправкой на перевозчика
                  (экспресс быстрее, почта медленнее и разбросаннее), округ (Сибирь и Дальний Восток, север — дольше),
                  снегопады (недели зимы в северных и восточных округах) и распродажи; приезд — в рабочие часы по
                  местному времени. `estimated_at` — обещанная дата (22:00 местного дня; для пункта выдачи — когда заказ
                  придёт в пункт): ожидаемые сроки сборки и пути с небольшим запасом, без задержек — опоздание видно по
                  `shipments.delivered_at` позже обещанного.
                * **Возвраты** (`returns`) — после получения: причина, состояние товара, решение, возвращённая сумма (не
                  больше заплаченного за строку); годный товар возвращается на склад последней мили в продажу
                  (`customer_return` с `ref_type = return`), брак — списывается. Не забранные и отказанные заказы
                  возвращаются на склад так же (`ref_type = order`). Замена и ремонт — вне таблиц заказа.
                * **Отзывы** (`reviews`) — после получения; оценка, ответ магазина или продавца (`answered_at`), текст — из
                  шаблонов фраз (без имён и марок), часть — без текста.
                * **Сессии** (`sessions`, `session_events`) — журнал веб-аналитики: в него попадают только посетители,
                  согласившиеся на аналитику (в приложении — чаще, чем на сайте), поэтому сессия есть лишь у части заказов
                  с сайта и из приложения (`orders.session_id`; у остальных и у телефонных заказов — пусто). Сессия заказа:
                  поиск, просмотры, добавления в корзину, убранные строки, оформление (`checkout` — в момент создания
                  заказа), попытки оплаты. Остальные сессии — без заказа: большей частью заход на одну страницу, ещё
                  просмотр каталога и брошенная корзина (часть доходит до оформления); больше половины — без входа
                  (`customer_id` пусто). Поисковые запросы — слова видов, категорий и моделей, с опечатками, транслитом и
                  в неверной раскладке.
                * **«Сейчас»** — заказы последних дней ещё в пути: статус и моменты — на «сейчас», будущих моментов нет
                  (кроме `estimated_at` и плана отгрузки `planned_at`).

                Узоры заказов:

                * сезонность и пики распродаж, неделя и сутки по местному времени;
                * концентрация выручки на небольшой части товаров и длинный хвост;
                * «покупают вместе» — устройство и аксессуары к нему встречаются в одном заказе заметно чаще случайного;
                * «фальшивая скидка» видна и в заказах: скидка по акции — от поднятой перед ней цены;
                * один продавец маркетплейса — с заметно большей долей возвратов, низкими оценками, опозданиями и отказами;
                * задержки доставки по округу, перевозчику и неделе (снег, распродажи); опоздания против обещанной даты;
                * удержание по когортам и крупные редкие заказы организаций;
                * воронка сессии и брошенные корзины;
                * рассрочка — у дорогих заказов;
                * смена ставки НДС 01.01.2026 в строках и заказах.

                Заложенные нарушения заказов (малая доля): недопустимые переходы статусов в журнале; двойное списание
                за заказ (часть — потом возвращена); «проверка карт» — серии мелких авторизаций разными попытками у новых
                аккаунтов с неоплаченным заказом; заказы на один адрес от разных клиентов.

                """;
    }
}
