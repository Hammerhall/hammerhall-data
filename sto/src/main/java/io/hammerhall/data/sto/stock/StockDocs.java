package io.hammerhall.data.sto.stock;

import java.util.List;
import java.util.Map;

/** Раздел SOURCE.md о складе и поставках — качественно, без долей и чисел заложенного. */
public final class StockDocs {
    private StockDocs() {
    }

    /** Текст раздела; пусто, если таблиц склада в прогоне нет. */
    public static String section(List<Map<String, Object>> files) {
        boolean stock = false, orders = false;
        for (Map<String, Object> f : files) {
            if ("stock_movements".equals(f.get("table"))) stock = true;
            if ("orders".equals(f.get("table"))) orders = true;
        }
        if (!stock) return "";
        StringBuilder sb = new StringBuilder();
        sb.append("## Склад и поставки\n\n");
        sb.append("* **Заказы поставщикам** (`purchase_orders`) — магазин заказывает товар на хаб, а у региональных\n")
                .append("  дистрибьюторов и производителей — прямо на РЦ их округа. Точка заказа и цель — по прогнозу спроса на\n")
                .append("  срок поставки и период до следующего заказа, со страховым запасом; поставщик принимает заказы в свои\n")
                .append("  дни недели, в нерабочие дни заказов и поставок нет. Ожидаемая дата — размещение плюс\n")
                .append("  `lead_time_days` поставщика; надёжность — доля поставок в срок: у менее надёжных чаще опоздания,\n")
                .append("  недопоставки (`partially_received`, у партии `qty` меньше `ordered_qty`) и отмены. Статус — на конец\n")
                .append("  фактов: заказы, не дошедшие к «сейчас», — в пути (`received_at` пусто, партии без приёмки и движений).\n");
        sb.append("* **Входящие остатки** — товар, лежавший на складах к началу периода, оформлен заказами с\n")
                .append("  `purpose = opening`: размещены, ожидались и приняты в первую секунду периода, сразу в ячейки, на каждый\n")
                .append("  склад, включая городские. Заказ, где все строки — первая поставка товара на склад (чаще всего\n")
                .append("  новинки), — `launch`, остальное — `replenishment`.\n");
        sb.append("* **Партии** (`batches`) — строка заказа поставщику, со своей закупочной ценой за штуку без НДС\n")
                .append("  (`unit_cost`): ниже розницы на наценку группы товаров, растёт со временем (инфляция закупочных цен), у\n")
                .append("  разных поставщиков разная, с 01.12.2026 у охваченных видов включает технологический сбор. У одного\n")
                .append("  товара — партии с разной ценой, поэтому себестоимость по FIFO и по средней расходятся. Партии продавцов\n")
                .append("  FBO (`seller_id`) — их поставки на склад магазина.\n");
        sb.append("* **Движения** (`stock_movements`) — журнал со знаком, id растут вместе со временем. Приёмка — в зону\n")
                .append("  приёмки (`receipt`, ячейка пуста), через несколько часов — размещение парами `move` (минус из зоны\n")
                .append("  приёмки, плюс в ячейки; в ячейке — несколько товаров, пока хватает предельного веса и объёма).\n")
                .append("  Переброски хаб → РЦ → городские склады — парами `transfer_out` / `transfer_in` с одним `ref_id`, в пути\n")
                .append("  от нескольких часов до полутора недель (Дальний Восток). Отбор под строку заказа — `pick` из ячеек по\n")
                .append("  FIFO: первой уходит старшая по приёмке партия; `ship` — отгрузка прямо из зоны приёмки, мимо ячеек\n")
                .append("  (так уходят строки, ждавшие поступления). Возврат покупателя — `customer_return`: годный товар — снова в\n")
                .append("  ячейку той же партии, брак — в зону возвратов и через сутки `writeoff`. Пересчёты — `inventory`\n")
                .append("  (расхождения) и `writeoff` неликвида снятых с продажи моделей. Номера переброски и пересчёта в `ref_id` —\n")
                .append("  номера документов, отдельных таблиц у них нет. Остаток по (склад, товар, партия) на момент — сумма `qty`\n")
                .append("  движений до него.\n");
        sb.append("* **Ассортимент складов** — по спросу: хаб держит весь ассортимент магазина (товары с совсем редким\n")
                .append("  спросом — под заказ), РЦ — шире, городской склад — ходовую часть. Покупателя обслуживает ближайший\n")
                .append("  городской склад, нет там — РЦ округа, нет и там — хаб. В малых профилях спрос меньше, и городские склады\n")
                .append("  и РЦ держат меньше позиций.\n\n");
        sb.append("Узоры склада и поставок:\n\n");
        sb.append("* нехватки и предзаказы у ходовых новинок: первая поставка приходит через срок поставщика после запуска и\n")
                .append("  меньше спроса — строки ждут поступления, часть уходит прямо с приёмки;\n");
        sb.append("* переброски на РЦ и городские склады за пару недель до 11.11, «чёрной пятницы» и Нового года;\n");
        sb.append("* сезонный запас: кондиционеры и вентиляторы — к лету, обогреватели — к зиме, ноутбуки и всё для учёбы — к\n")
                .append("  сентябрю; после сезона остатки тают медленно;\n");
        sb.append("* в новогодние каникулы поставщики не возят — запасы проседают;\n");
        sb.append("* закупочные цены растут, у одного товара — партии с разной ценой;\n");
        sb.append("* у менее надёжных поставщиков — опоздания, недопоставки и отмены;\n");
        sb.append("* по журналу изредка встречается отрицательный остаток ячейки и партии после пересчёта — ошибка проведения,\n")
                .append("  которую исправляет следующий пересчёт.\n");
        if (!orders) {
            sb.append("\nЗаказов покупателей в этом прогоне нет: расход склада — синтетический спрос того же календаря и тех же\n")
                    .append("товаров; `ref_type = order` и `return` ссылаются на номера его заказов и возвратов.\n");
        }
        sb.append('\n');
        return sb.toString();
    }
}
