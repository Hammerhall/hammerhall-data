    private static final String[] SURNAME_M;
    private static final String[] SURNAME_F;
    private static final double[] SURNAME_CUM;
    private static final double[][] MALE_CUM = new double[3][], FEMALE_CUM = new double[3][];

    static {
        String[] parts = SURNAMES_SRC.trim().split("\\s+");
        SURNAME_M = new String[parts.length];
        SURNAME_F = new String[parts.length];
        SURNAME_CUM = new double[parts.length];
        Set<String> seen = new TreeSet<>();
        double c = 0;
        for (int i = 0; i < parts.length; i++) {
            String[] kv = parts[i].split(":");
            if (!seen.add(kv[0])) throw new IllegalStateException("повтор фамилии " + kv[0]);
            SURNAME_M[i] = kv[0];
            SURNAME_F[i] = feminine(kv[0]);
            c += Double.parseDouble(kv[1]);
            SURNAME_CUM[i] = c;
        }
        for (First[] list : new First[][]{MALE, FEMALE}) {
            Set<String> s = new TreeSet<>();
            for (First x : list) if (!s.add(x.name)) throw new IllegalStateException("повтор имени " + x.name);
        }
        for (int era = 0; era < 3; era++) {
            MALE_CUM[era] = cum(MALE, era);
            FEMALE_CUM[era] = cum(FEMALE, era);
        }
    }

    private static double[] cum(First[] list, int era) {
        double[] out = new double[list.length];
        double c = 0;
        for (int i = 0; i < list.length; i++) {
            c += era == 0 ? list[i].wOld : (era == 1 ? list[i].wMid : list[i].wYoung);
            out[i] = c;
        }
        return out;
    }

    /** Индекс по накопленным весам (двоичный поиск; веса — положительные). */
    static int pickCum(Rng r, double[] cum) {
        double x = r.nextDouble() * cum[cum.length - 1];
        int i = Arrays.binarySearch(cum, x);
        if (i < 0) i = -i - 1;
        return Math.min(i, cum.length - 1);
    }

    private static int era(int birthYear) {
        return birthYear < 1970 ? 0 : (birthYear < 1990 ? 1 : 2);
    }

    /**
     * Женская форма фамилии: -ов/-ев/-ёв/-ин/-ын → +а; -ский/-цкий → -ская/-цкая; -ой/-ый → -ая; прочие (-ко, -ых,
     * -ик, согласная) не склоняются.
     */
    public static String feminine(String m) {
        if (m.endsWith("ий") && (m.endsWith("ский") || m.endsWith("цкий"))) return m.substring(0, m.length() - 2) + "ая";
        if (m.endsWith("ой") || m.endsWith("ый")) return m.substring(0, m.length() - 2) + "ая";
        if (m.endsWith("ов") || m.endsWith("ев") || m.endsWith("ёв") || m.endsWith("ин") || m.endsWith("ын")) return m + "а";
        return m;
    }

