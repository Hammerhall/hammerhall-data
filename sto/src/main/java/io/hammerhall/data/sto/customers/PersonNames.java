    /** Имя по полу и году рождения — индекс в списке пола. */
    public static int pickFirst(Rng r, boolean female, int birthYear) {
        return pickCum(r, female ? FEMALE_CUM[era(birthYear)] : MALE_CUM[era(birthYear)]);
    }

    public static String first(boolean female, int idx) {
        return (female ? FEMALE : MALE)[idx].name;
    }

    public static int pickSurname(Rng r) {
        return pickCum(r, SURNAME_CUM);
    }

    public static String surname(int idx, boolean female) {
        return female ? SURNAME_F[idx] : SURNAME_M[idx];
    }

    /** Отчество: имя отца — по поколению отца (≈ на 28 лет старше). */
    public static String patronymic(Rng r, boolean female, int birthYear) {
        First father = MALE[pickCum(r, MALE_CUM[era(birthYear - 28)])];
        return female ? father.patrF : father.patrM;
    }

    /** Имя известно генератору (для проверки согласования с полом). */
    public static boolean isFirst(String name, boolean female) {
        for (First x : female ? FEMALE : MALE) if (x.name.equals(name)) return true;
        return false;
    }

    /** Фамилия — из списка и в форме своего пола. */
    public static boolean isSurname(String name, boolean female) {
        for (int i = 0; i < SURNAME_M.length; i++) if ((female ? SURNAME_F[i] : SURNAME_M[i]).equals(name)) return true;
        return false;
    }

