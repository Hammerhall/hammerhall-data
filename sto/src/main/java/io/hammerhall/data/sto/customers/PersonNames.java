    private static boolean badCluster(String s) {
        int cons = 0;
        for (int i = 0; i < s.length(); i++) {
            char ch = Character.toLowerCase(s.charAt(i));
            boolean v = VOWELS.indexOf(ch) >= 0;
            if (v && i > 0 && VOWELS.indexOf(Character.toLowerCase(s.charAt(i - 1))) >= 0) return true;
            cons = v ? 0 : cons + 1;
            if (cons >= 3) return true;
        }
        return false;
    }

    /**
     * Корень выдуманного названия организации (кириллица, 5–9 букв): из слогов, без стечения трёх согласных и двух
     * гласных подряд, не имя человека и не похожий на настоящую марку (латинская запись сверяется
     * {@link Names#resemblesReal}); {@code null} — попытка не удалась, тянуть ещё.
     */
    public static String orgRoot(Rng r) {
        String s = ORG_START[r.nextInt(ORG_START.length)] + ORG_MID[r.nextInt(ORG_MID.length)]
                + ORG_END[r.nextInt(ORG_END.length)];
        if (s.length() < 5 || s.length() > 9 || badCluster(s)) return null;
        if (isFirst(s, true) || isFirst(s, false) || mentionsInternal(s)) return null;
        if (Names.resemblesReal(Names.toLatin(s))) return null;
        return s;
    }
