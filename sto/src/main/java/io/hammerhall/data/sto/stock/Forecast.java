package io.hammerhall.data.sto.stock;

import io.hammerhall.data.core.time.RuCalendar;
import io.hammerhall.data.sto.catalog.Catalog;

import java.time.LocalDate;

/**
 * Прогноз спроса для пополнения: сколько штук товара магазина (1P) в сутки ждать по всей стране, в масштабе профиля.
 * Движок берёт гладкую часть {@link #baseRate} раз в неделю (с шагом 7 дней вперёд) и умножает на календарь
 * ({@link RuCalendar#demand}: месяц, день недели, события) — так видно и сезон, и пики событий впереди. Сверху движок
 * сам поправляет прогноз по фактическому спросу последних недель (если источник расхода живёт иначе, чем прогноз).
 *
 * <p>Прогноз вправе знать только товары, уже запущенные на дату вызова (стабильность при продлении периода).
 */
public interface Forecast {
    /** Ожидаемые штуки 1P в сутки без календаря (популярность × жизненный цикл × доля магазина × масштаб). */
    double baseRate(Catalog.Product p, LocalDate d);

    /** Сезон спроса товара для календаря; по умолчанию — сезон вида. */
    default RuCalendar.Season season(Catalog.Product p) {
        return p.kind.season;
    }

    /** Масштаб профиля, к которому приведён прогноз (для решений об ассортименте в «полных» штуках). */
    double scale();
}
